//! Neural-I/O groups from the pinned MaleCNS artifact.
//!
//! `assets/neuromechfly/male_cns_v1_neural_io.json` selects annotated
//! populations by cell type from Janelia's own annotation table. Every group
//! resolves to real MaleCNS body IDs, all of which are present in the pack
//! (the artifact reports zero missing roots). Nothing here is fabricated
//! wiring: these are the published motor neurons, descending neurons and
//! sensory receptor populations, used as explicit readout and stimulation
//! interfaces.

use crate::lif::DT_MS;
use crate::pack::Connectome;
use anyhow::{Context, Result};
use serde_json::Value;
use std::collections::HashMap;
use std::path::{Path, PathBuf};

/// Neuron-group annotations shipped with the repo (from the MaleCNS /
/// neuromechanistic-fly release). Override with `FLYVERSE_IO_JSON`.
pub const IO_JSON: &str = "assets/male_cns_v1_neural_io.json";

/// Resolve the group annotation table: `$FLYVERSE_IO_JSON`, else IO_JSON.
pub fn io_json_path() -> PathBuf {
    std::env::var("FLYVERSE_IO_JSON")
        .map(PathBuf::from)
        .unwrap_or_else(|_| PathBuf::from(IO_JSON))
}

/// Physiological full scale of a flight POWER motor neuron's firing rate,
/// Hz per neuron.
///
/// The flight power muscles (DLM/DVM) are *asynchronous* indirect flight
/// muscles: the wingbeat is generated by the thorax's own stretch-activated
/// oscillator at ~200 Hz and is decoupled from the motor-neuron firing rate,
/// which only sets the muscle's activation level. The consequence is that the
/// motor neurons fire far BELOW the wingbeat frequency:
///
/// * Gordon & Dickinson (2006), PNAS 103(11):4311-4315,
///   doi:10.1073/pnas.0510109103: "The motor neurons of the A-IFMs fire at a
///   rate (approximately 5 Hz in *Drosophila*) well below contraction frequency
///   (approximately 200 Hz)"; mechanical power rises and falls with the firing
///   frequency, and the recorded spike frequency went "up to approximately
///   20 Hz" during visually elicited manoeuvres (2-fold change in power per
///   3-fold change in rate).
/// * Lehmann, Skandalis & Berthe (2013), J. R. Soc. Interface 10:20121050,
///   doi:10.1098/rsif.2012.1050, and Lehmann & Bartussek (2016), J. Comp.
///   Physiol. A 202, doi:10.1007/s00359-016-1133-9: "the A-IFM's low spike
///   frequency between 5 and 20 Hz maintains rather constant intramuscular
///   calcium levels during flight"; power is linear in intramuscular calcium
///   (R^2 ~ 0.95) over 20-120 W/kg at 56-79 nM.
/// * "Gap junctions desynchronize a neural circuit to stabilize insect
///   flight", Nature 618:118-124 (2023), doi:10.1038/s41586-023-06099-0: each
///   of the five identified DLM motor neurons "fires only every approximately
///   20th to 40th wingbeat" (5-10 Hz at a 200 Hz wingbeat); the tethered-flight
///   working range is "approximately 3-12 Hz" and the f-I curve is linear over
///   3-30 Hz, i.e. tuned to that range.
///
/// So the actuator's full scale -- the rate at which a flight power muscle is
/// maximally activated and the wing gives full stroke amplitude -- is **20 Hz**
/// per neuron, not the rate a spike-count window can arithmetically express.
pub const POWER_MN_MAX_HZ: f32 = 20.0;

/// The physiological full scale of a read-out, Hz per neuron, or `None` when
/// the group has no physiological anchor.
///
/// `None` groups keep the window's arithmetic ceiling as their reference, which
/// at least leaves the read-out a fraction of the pool in 0..1. Only the
/// flight-power pools are anchored so far: they are the ones that drive an
/// actuator (`body.rs` reads them as the muscle activation `a`), so their scale
/// decides whether the fly can fly, and 500 Hz of motor drive is not a physical
/// quantity a muscle can be asked for. See `POWER_MN_MAX_HZ`.
pub fn phys_full_scale_hz(name: &str) -> Option<f32> {
    match name {
        "motor_flight_power_left" | "motor_flight_power_right" => Some(POWER_MN_MAX_HZ),
        _ => None,
    }
}

