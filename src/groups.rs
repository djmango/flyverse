/// Physiological FULL-STROKE firing rate of a flight POWER motor neuron, Hz
/// per neuron. This is the denominator that turns the pool's measured firing
/// rate into the actuator command `a` in 0..1 that `body.rs` reads.
///
/// The flight power muscles (DLM/DVM) are *asynchronous* indirect flight
/// muscles: the wingbeat is generated by the thorax's own stretch-activated
/// oscillator at ~200 Hz and is decoupled from the motor-neuron firing rate,
/// which only sets the muscle's activation level. The consequence is that the
/// motor neurons fire far BELOW the wingbeat frequency:
///
/// * Gordon & Dickinson (2006), PNAS 103(11):4311-4315,
///   doi:10.1073/pnas.0510109103: "The motor neurons of the A-IFMs fire at a
///   rate (approximately 5 Hz in *Drosophila*) well below contraction frequency
///   (approximately 200 Hz)"; mechanical power rises and falls with the firing
///   frequency, and the recorded spike frequency went "up to approximately
///   20 Hz" during visually elicited manoeuvres.
/// * Lehmann, Skandalis & Berthe (2013), J. R. Soc. Interface 10:20121050,
///   doi:10.1098/rsif.2012.1050: "the A-IFM's low spike frequency between 5 and
///   20 Hz maintains rather constant intramuscular calcium levels during
///   flight"; power is linear in intramuscular calcium over 20-120 W/kg.
/// * Huerkey, Schueler, Ryglewski, Duch, Schreiber, Silies et al. (2023), "Gap
///   junctions desynchronize a neural circuit to stabilize insect flight",
///   *Nature* 618:118-124, doi:10.1038/s41586-023-06099-0: each of the five
///   identified DLM motor neurons "fires only every approximately 20th to 40th
///   wingbeat" (5-10 Hz at a 200 Hz wingbeat), the tethered-flight working range
///   is "approximately 3-12 Hz" (Fig. 1c), and the measured f-I curve is linear
///   over 3-30 Hz, i.e. tuned to that range.
///
/// **Why 12 Hz, and not the 20 Hz this anchor used to carry.** `a = 1` is the
/// FULL-STROKE endpoint — the spec pins it at `F_lift/(W/2) ~ 1.2`
/// (physical-model-spec.md §6.5, derived from the mandatory self-check in §6.3)
/// — so this constant is the rate at which the muscle reaches maximal
/// activation and the wing its full stroke. The measured in-flight working
/// range tops out at **12 Hz**; the ~20 Hz band is reached only in elicited
/// manoeuvres, and the f-I curve stays linear well past it, so 20 Hz is a
/// manoeuvre excursion rather than the activation ceiling. Putting the
/// full-stroke endpoint at the top of the measured in-flight band keeps the
/// whole normal flight envelope inside the command's graded range; putting it
/// at 20 Hz makes the animal's entire sustained range a fraction of full scale
/// and any manoeuvre saturate. See `POWER_MN_BAND_LO_HZ`,
/// `POWER_MN_BAND_HI_HZ`.
pub const POWER_MN_FULL_STROKE_HZ: f32 = 12.0;

/// The measured in-flight working range of the flight power motor neurons, Hz
/// per neuron. [M] Huerkey et al. 2023, *Nature* 618:118-124, Fig. 1c:
/// "approximately 3-12 Hz"; Gordon & Dickinson 2006 put the sustained value at
/// "approximately 5 Hz". Anything the model reports outside this band is
/// outside the range the animal was measured to fly at.
pub const POWER_MN_BAND_LO_HZ: f32 = 3.0;
pub const POWER_MN_BAND_HI_HZ: f32 = 12.0;

/// The measured MAXIMUM rate a flight power motor neuron reaches, Hz per
/// neuron: the "up to approximately 20 Hz" seen during visually elicited
/// manoeuvres (Gordon & Dickinson 2006), not the ceiling of normal flight. It
/// is reported by `mn-audit` as the manoeuvre band and is deliberately **not**
/// the actuator's full scale — see `POWER_MN_FULL_STROKE_HZ`.
pub const POWER_MN_MANOEUVRE_MAX_HZ: f32 = 20.0;

/// Time constant over which a flight POWER pool's firing rate is estimated
/// before it becomes the actuator command, seconds. [M]-anchored.
///
/// The A-IFM reads out the *tonic* motor-neuron rate, not a coincidence inside
/// one 2 ms window: the muscle integrates the arriving spikes over its own
/// transduction time, and those times are measured — DLM fibre action-potential
/// decay tau ~ 14 ms, myoplasmic Ca2+ decay tau ~ 79 ms, wingbeat-change tau
/// ~ 83 ms (Huerkey et al. 2023, *Nature* 618:118-124, Fig. 4b). This uses the
/// calcium decay, the slowest of the three, which is the one the muscle's
/// activation level follows.
///
/// The alternative — estimating the rate from a single 2 ms control window —
/// makes ONE spike read as `1000/2/12 = 41.7` Hz/neuron, several times any
/// rate a flight muscle is asked for. The command then saturates on the first
/// spike of a window and `a` tracks `P(>=1 member fires)`, which is a
/// compressive function of the true rate; no rate-to-force map can recover the
/// measured relation from it.
pub const MOTOR_RATE_TAU_S: f32 = 0.080;

/// The physiological full scale of a read-out, Hz per neuron, or `None` when
/// the group has no physiological anchor.
///
/// `None` groups keep the window's arithmetic ceiling as their reference, which
/// at least leaves the read-out a fraction of the pool in 0..1. Only the
/// flight-power pools are anchored so far: they are the ones that drive an
/// actuator (`body.rs` reads them as the muscle activation `a`), so their scale
/// decides whether the fly can fly, and 500 Hz of motor drive is not a physical
/// quantity a muscle can be asked for. See `POWER_MN_FULL_STROKE_HZ`.
pub fn phys_full_scale_hz(name: &str) -> Option<f32> {
    match name {
        "motor_flight_power_left" | "motor_flight_power_right" => Some(POWER_MN_FULL_STROKE_HZ),
        _ => None,
    }
}

